/**
 * Issues Holdr license keys (Ed25519-signed, verified offline by the app).
 *
 *   node scripts/license-tool.mjs init
 *     Creates the signing key pair once. The private key is stored OUTSIDE the
 *     repository (default: ~/.holdr-license/private-key.pem); the public key is
 *     written to app/src-tauri/src/license_public_key.rs and must be committed.
 *
 *   node scripts/license-tool.mjs issue --licensee "Erika Muster" --plan lifetime
 *   node scripts/license-tool.mjs issue --licensee "Erika Muster" --plan subscription --expires 2027-10-31
 *     Prints a license key for a customer.
 *
 * Options: --key <path> overrides the private key location (or HOLDR_LICENSE_KEY).
 * Never commit or share the private key: anyone who has it can create licenses.
 *
 * ⚠️ Issuing is blocked while the app uses Yahoo Finance data, which must not be
 * used commercially.
 */
import {
  createPrivateKey,
  generateKeyPairSync,
  randomUUID,
  sign,
} from "node:crypto";
import {
  chmodSync,
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { homedir } from "node:os";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const PUBLIC_KEY_FILE = join(
  ROOT,
  "app",
  "src-tauri",
  "src",
  "license_public_key.rs",
);
const PLANS = new Set(["lifetime", "subscription"]);
const SERVICES_FILE = join(ROOT, "app", "src", "platform", "services.ts");

function main() {
  const [command, ...rest] = process.argv.slice(2);
  const options = parseOptions(rest);
  const keyPath = resolve(
    options.key ??
      process.env.HOLDR_LICENSE_KEY ??
      join(homedir(), ".holdr-license", "private-key.pem"),
  );

  if (command === "init") return init(keyPath, Boolean(options.force));
  if (command === "issue") return issue(keyPath, options);
  console.error(
    "Usage: node scripts/license-tool.mjs init | issue --licensee <name> --plan lifetime|subscription [--expires YYYY-MM-DD]",
  );
  process.exit(2);
}

function init(keyPath, force) {
  if (!relative(ROOT, keyPath).startsWith("..")) {
    fail("The private key must not be stored inside the repository.");
  }
  if (existsSync(keyPath) && !force) {
    fail(
      `A private key already exists at ${keyPath}. Use --force only if you really want to replace it:\nall licenses issued so far would stop working.`,
    );
  }

  const { publicKey, privateKey } = generateKeyPairSync("ed25519");
  mkdirSync(dirname(keyPath), { recursive: true });
  writeFileSync(keyPath, privateKey.export({ type: "pkcs8", format: "pem" }), {
    mode: 0o600,
  });
  chmodSync(keyPath, 0o600);

  const raw = Buffer.from(publicKey.export({ format: "jwk" }).x, "base64url");
  const bytes = [...raw].map((b) => `0x${b.toString(16).padStart(2, "0")}`);
  const rows = [];
  for (let i = 0; i < bytes.length; i += 8)
    rows.push(`    ${bytes.slice(i, i + 8).join(", ")},`);
  writeFileSync(
    PUBLIC_KEY_FILE,
    `//! Public key for verifying license keys.
//!
//! Generated by \`node scripts/license-tool.mjs init\`, which also stores the
//! matching private key outside the repository. \`None\` means that no key has
//! been set up yet, so every license key is rejected.

pub const PUBLIC_KEY: Option<[u8; 32]> = Some([
${rows.join("\n")}
]);
`,
  );

  console.log(
    `✓ Private key saved to ${keyPath} (keep it safe and make a backup).`,
  );
  console.log(
    `✓ Public key written to app/src-tauri/src/license_public_key.rs (commit this file).`,
  );
}

function issue(keyPath, options) {
  // Selling licenses requires a market data source that allows commercial use.
  if (
    readFileSync(SERVICES_FILE, "utf8").includes("market/yahoo") &&
    !options["test-only"]
  ) {
    fail(
      "Refusing to issue a license: Holdr still uses Yahoo Finance, whose terms do not permit\n" +
        "commercial use. Holdr may only be offered free of charge until the market data provider\n" +
        'is replaced. For local tests only, add --test-only.',
    );
  }
  if (!existsSync(keyPath))
    fail(`No private key at ${keyPath}. Run "init" first.`);
  const licensee = options.licensee?.trim();
  if (!licensee) fail("--licensee is required.");
  if (!PLANS.has(options.plan))
    fail("--plan must be lifetime or subscription.");
  if (
    options.plan === "subscription" &&
    !/^\d{4}-\d{2}-\d{2}$/.test(options.expires ?? "")
  ) {
    fail("Subscriptions need --expires YYYY-MM-DD.");
  }

  const payload = {
    id: randomUUID(),
    licensee,
    plan: options.plan,
    issuedAt: new Date().toISOString().slice(0, 10),
    expiresAt: options.plan === "subscription" ? options.expires : null,
  };
  const encoded = Buffer.from(JSON.stringify(payload)).toString("base64url");
  const signature = sign(
    null,
    Buffer.from(encoded),
    createPrivateKey(readFileSync(keyPath)),
  );

  console.log(`HOLDR-${encoded}.${signature.toString("base64url")}`);
  console.error(
    `(license ${payload.id} for ${licensee}, plan ${payload.plan}${payload.expiresAt ? ` until ${payload.expiresAt}` : ""})`,
  );
}

function parseOptions(args) {
  const options = {};
  for (let i = 0; i < args.length; i++) {
    const name = args[i].replace(/^--/, "");
    const next = args[i + 1];
    if (next === undefined || next.startsWith("--")) {
      options[name] = true;
    } else {
      options[name] = next;
      i++;
    }
  }
  return options;
}

function fail(message) {
  console.error(message);
  process.exit(1);
}

main();
